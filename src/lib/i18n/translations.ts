export type TranslateVars = Record<string, string | number>;

// Shared by both the SaaS app's global LocaleProvider and the independent, portfolio-scoped
// PortfolioLocaleProvider — same lookup/interpolation logic, two separate language states.
export function createTranslator(lang: AppLocale) {
  return (key: string, vars?: TranslateVars) => {
    const template = messages[lang][key] ?? messages.en[key] ?? key;
    if (!vars) return template;
    return Object.entries(vars).reduce(
      (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
      template
    );
  };
}
